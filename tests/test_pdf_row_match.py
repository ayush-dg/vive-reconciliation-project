class TestRereader(_PdfCase):
    """A disputed scanned cell is accepted only when an independent re-read
    EQUALS the extracted value."""

    class _Fixed(m._Rereader):
        def __init__(self, answer):
            super().__init__("unused.pdf", time.monotonic() + 30)
            self.answer = answer

        def _ocr(self, page_number, box, whitelist, psm):
            return [{"text": self.answer, "x0": box[0], "x1": box[2], "top": box[1], "bottom": box[3]}]

    def _misread_table(self):
        path = self.pdf([store_page([("Store A", 3, "797.39", STORE_A)])])
        pages = m.read_pdf_lines(path)
        for page in pages:
            page["source"] = "ocr"  # pretend the page was scanned
            for line in page["lines"]:
                for w in line["words"]:
                    if w["text"] == "367808-1":
                        w["text"] = "3567808-1"  # what Tesseract read
                line["text"] = " ".join(w["text"] for w in line["words"])
        return m.build_table(pages)

    def test_equal_reread_is_accepted(self):
        matches, failures, log = m.match_rows(store_rows(STORE_A), self._misread_table(), reread=self._Fixed("367808-1"))
        self.assertEqual(failures, [])
        self.assertEqual(len(matches), 3)
        self.assertTrue(log[0]["accepted"])

    def test_different_reread_is_refused(self):
        matches, failures, log = m.match_rows(store_rows(STORE_A), self._misread_table(), reread=self._Fixed("567808-1"))
        self.assertEqual({f["problem"] for f in failures}, {"extra", "missing"})
        self.assertFalse(any(entry["accepted"] for entry in log))

    def test_without_a_rereader_the_misread_row_fails(self):
        _, failures, _ = m.match_rows(store_rows(STORE_A), self._misread_table())
        self.assertTrue(failures)

    def test_glued_row_number_and_date_are_split_but_a_date_never_is(self):
        split = m._split_row_number_from_date
        word = {"x0": 0.0, "x1": 10.0, "top": 0.0, "bottom": 1.0}
        self.assertEqual([w["text"] for w in split([dict(word, text="2308/19/26")])], ["23", "08/19/26"])
        self.assertEqual([w["text"] for w in split([dict(word, text="08/19/26")])], ["08/19/26"])


