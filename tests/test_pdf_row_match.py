class TestNortheastRunningBalanceTrace(unittest.TestCase):
    """Why STMT-5D1050A6 failed on Oct 1 and what passes now. The running
    balance accepts an unlabelled opening ONLY through chain_opening_balance
    (a scan's model previous_balance whose label is not a balance-forward
    label, src/validation/previous_balance.py), and only when every row's
    printed balance chains from it."""

    ROWS_OCT1 = [row("2524536", "08/12/26", 76.29, due=156.69), row("2531421", "08/29/26", 17.92, due=94.21)]
    CREDIT = row(None, "08/17/26", credit=80.40, due=76.29)

    def _gate(self, rows, opening):
        return validate_with_fallbacks(94.21, compute_statement_total_from_invoices(rows), rows,
                                       chain_opening_balance=opening)

    def test_oct1_stored_shape_breaks_at_row_one(self):
        # Oct 1: no model previous_balance (the field did not exist yet), so
        # the opening was 0 and the chain broke at position 1 (76.29 vs 156.69).
        result = self._gate(self.ROWS_OCT1[:1] + [self.CREDIT] + self.ROWS_OCT1[1:], None)
        attempt = next(a for a in result["detail"]["attempts"] if a["method"] == "running_balance")
        self.assertEqual(attempt["first_broken_row"]["position"], 1)
        self.assertEqual(result["status"], "mismatch")

    def test_credit_present_and_opening_from_the_model_passes(self):
        rows = self.ROWS_OCT1[:1] + [self.CREDIT] + self.ROWS_OCT1[1:]
        result = self._gate(rows, 80.40)
        self.assertEqual((result["status"], result["method"]), ("matches", "running_balance"))

    def test_opening_with_a_balance_that_does_not_chain_fails(self):
        # The opening is only accepted when EVERY row's printed balance
        # chains from it: one wrong balance and nothing passes.
        rows = self.ROWS_OCT1[:1] + [dict(self.CREDIT, amount_due=76.92)] + self.ROWS_OCT1[1:]
        result = self._gate(rows, 80.40)
        self.assertEqual(result["status"], "mismatch")

    def test_without_the_credit_the_rows_coincidentally_sum_to_the_total(self):
        # Recorded, not a fix: Bronze's two rows (76.29 + 17.92) equal the
        # printed 94.21 because the dropped credit equals the unlabelled
        # opening (80.40). The gate on Oct 1 saw all three model rows.
        result = self._gate(list(self.ROWS_OCT1), None)
        self.assertEqual((result["status"], result["method"]), ("matches", "primary"))

    def test_town_fair_shape_has_no_per_row_balance_so_no_opening_rule_applies(self):
        rows = [row("72838580", "08-20-26", 209.0), row(None, "08-24-26", credit=887.0)]
        result = validate_with_fallbacks(209.0, compute_statement_total_from_invoices(rows), rows,
                                         chain_opening_balance=887.0)
        self.assertEqual(result["status"], "mismatch")


