    def test_aging_buckets_alone_never_pass(self):
        # Rows sum to 195.50 but the printed total is 250.00; the aging boxes
        # print 200.00 + 50.00 = 250.00. Aging is corroboration only.
        lines = GOOD_LINES[:2]
        aging = [(X["desc"], 400, "CURRENT"), (X["charge"], 400, "OVER 30 DAYS"), (X["credit"], 400, "OVER 60 DAYS"),
                 (X["desc"], 414, "200.00"), (X["charge"], 414, "50.00"), (X["credit"], 414, "0.00")]
        path = self.pdf([statement_page(lines, total="250.00", extra=aging)])
        rows = good_rows()[:2]
        for r in rows:
            r["amount_due"] = None
        result = m.check_pdf_row_match(250.0, rows, pdf_path=path)
        self.assertFalse(result["passed"])
        self.assertTrue(any(e["equation"] == "aging" and not e["reconciles"] for e in result.get("equations", [])))

