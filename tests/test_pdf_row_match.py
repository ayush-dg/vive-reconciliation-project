_INTAKE = None


def intake():
    """Loaded lazily with os.environ restored (the notebook calls
    load_dotenv on import -- see test_oct1_intake_worker_web.py)."""
    global _INTAKE
    if _INTAKE is None:
        import importlib.util
        saved = dict(os.environ)
        try:
            spec = importlib.util.spec_from_file_location(
                "intake_pdf_row_match_test",
                os.path.join(os.path.dirname(__file__), "..", "notebooks", "01_document_intake.py"))
            module = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(module)
        finally:
            os.environ.clear()
            os.environ.update(saved)
        _INTAKE = module
    return _INTAKE


