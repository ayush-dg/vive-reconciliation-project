def write_pdf(pages):
    """pages: [[(x, y, text), ...], ...] -> path of a temporary text-layer PDF."""
    doc = fitz.open()
    for items in pages:
        page = doc.new_page(width=612, height=792)
        for x, y, text in items:
            page.insert_text((x, y), text, fontsize=9)
    f = tempfile.NamedTemporaryFile(suffix=".pdf", delete=False)
    f.close()
    doc.save(f.name)
    return f.name


def statement_page(lines, total=None, top=120, letterhead=True, extra=()):
    """One statement page: letterhead, the column header, one PDF line per
    dict in `lines` (keys of X), an optional TOTAL DUE line and any extra
    (x, y, text) items."""
    items = []
    if letterhead:
        items += [(40, 50, "SYNTHETIC PARTS SUPPLY"), (40, 62, "123 Example Road Springfield"),
                  (40, 74, "STATEMENT OF ACCOUNT"), (40, 86, "Customer Test Body Shop")]
    items += [(X[k], top, label) for k, label in HEADER]
    y = top + 16
    for line in lines:
        for key, value in line.items():
            items.append((X[key], y, value))
        y += 14
    if total is not None:
        items.append((X["desc"], y + 10, "TOTAL DUE"))
        items.append((X["bal"], y + 10, total))
    items += list(extra)
    return items


def row(number, date, charge=None, credit=None, due=None):
    """An extracted row in the gate's invoice shape."""
    return {"invoice_number": number, "invoice_date": date, "outstanding_amount": charge,
            "credit": credit, "amount_due": due}


