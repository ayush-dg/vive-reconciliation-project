def store_page(sections, group_total="9,999.99"):
    """sections: [(store, count, amount_due, [(no, date, invoice, amount), ...])]."""
    items = [(40, 40, "SYNTHETIC GROUP Monthly Statement"), (40, 52, "Customer Number 1305810"),
             (300, 64, f"Total Amount Due ${group_total}")]
    y = 90
    for store, count, amount_due, lines in sections:
        items.append((40, y, f"{store} Invoices: {count} | Amount Due: ${amount_due}"))
        y += 14
        for key, label in (("no", "#"), ("date", "Invoice Date"), ("inv", "Invoice#"), ("buy", "Purchases"),
                           ("pay", "Payments"), ("bal", "Balance")):
            items.append((SX[key], y, label))
        y += 14
        for no, date, invoice, amount in lines:
            items += [(SX["no"], y, str(no)), (SX["date"], y, date), (SX["inv"], y, invoice),
                      (SX["buy"], y, f"${amount}"), (SX["bal"], y, f"${amount}")]
            y += 13
        y += 10
    return items


